//! The reviewed publication registry for the canonical library.
//!
//! A publication is the unit that a book view, a source facet, and a Section 15
//! notice share. Pf Data and PSRD-Data spell the same book differently, so the
//! canonical build may not use either dataset's spelling directly: one book must
//! have one source id, or it appears twice in the book view.
//!
//! The registry is generated from the pinned inventory with
//! `cargo xtask data-publications`, reviewed, and committed. A publication that
//! exists in PSRD's sixteen books keeps the PSRD source id; every other
//! publication uses [`crate::slug::slug_segment`] of its Pf Data title. The same
//! folding aliases the alias gate uses (`PRPG Core Rulebook`,
//! `Pathfinder RPG Bestiary`, `GameMastery Guide`) apply here, so a title cannot
//! pass one gate and fail the other.

use crate::alias::canonical_source_id;
use crate::config::SourceConfig;
use crate::pf_data::Inventory;
use crate::slug::slug_segment;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

/// Current registry format.
pub const REGISTRY_FORMAT: u32 = 1;
/// Committed path, relative to the repository root.
pub const REGISTRY_PATH: &str = "sources/canonical/publications.toml";

/// One publication's canonical identity.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Publication {
    /// Canonical source id, such as `core-rulebook`.
    pub source: String,
    /// Display title used by the catalog and the book view.
    pub title: String,
}

/// The reviewed registry.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Registry {
    pub version: u32,
    /// Pf Data publication title to canonical identity. Sorted by title.
    pub publication: BTreeMap<String, Publication>,
}

impl Registry {
    pub fn parse(text: &str) -> Result<Self, String> {
        let registry: Self = toml::from_str(text).map_err(|e| e.to_string())?;
        if registry.version != REGISTRY_FORMAT {
            return Err(format!(
                "publication registry version is {}; this compiler reads {REGISTRY_FORMAT}",
                registry.version
            ));
        }
        for (title, row) in &registry.publication {
            if title.trim().is_empty() || title != title.trim() {
                return Err(format!("publication title {title:?} is empty or padded"));
            }
            if row.source.is_empty() || row.title.trim().is_empty() {
                return Err(format!(
                    "publication {title:?} has an empty source or title"
                ));
            }
        }
        Ok(registry)
    }

    pub fn load(path: &Path) -> Result<Self, String> {
        let text = std::fs::read_to_string(path)
            .map_err(|e| format!("cannot read {}: {e}", path.display()))?;
        Self::parse(&text).map_err(|e| format!("invalid {}: {e}", path.display()))
    }

    /// Serializes with a fixed header and sorted rows.
    pub fn to_bytes(&self) -> Result<Vec<u8>, String> {
        let mut text = String::from(
            "# Canonical publication registry, generated by `cargo xtask data-publications`.\n\
             # Reviewed and committed. One Pf Data publication title maps to one canonical\n\
             # source id. A title in PSRD's sixteen books keeps the PSRD source id; every\n\
             # other title uses slug_segment of the Pf Data title. The build fails when an\n\
             # in-scope Pf Data publication has no row here.\n\n",
        );
        text.push_str(&toml::to_string(self).map_err(|e| e.to_string())?);
        Ok(text.into_bytes())
    }

    /// Every canonical source id present in the registry.
    pub fn source_ids(&self) -> BTreeSet<&str> {
        self.publication
            .values()
            .map(|row| row.source.as_str())
            .collect()
    }

    /// The registry row for one Pf Data publication title.
    pub fn get(&self, title: &str) -> Option<&Publication> {
        self.publication.get(title)
    }
}

/// Every publication title the pinned inventory names.
///
/// This deliberately includes publications that only appear on out-of-scope
/// records. A record can carry several publications and stay in scope when at
/// least one is in scope, and a `copy` record can inherit a publication from a
/// companion record. A registry row for such a title is harmless; a missing row
/// would make the canonical build fail on a publication that conversion actually
/// uses.
pub fn inventory_publications(inv: &Inventory) -> BTreeSet<String> {
    inv.by_publication.keys().cloned().collect()
}

/// Generates the registry from the pinned inventory and PSRD's reviewed book list.
pub fn generate(inv: &Inventory, psrd_source_config: &Path) -> Result<Registry, Vec<String>> {
    let cfg = SourceConfig::load(psrd_source_config).map_err(|e| vec![e])?;
    let psrd: BTreeMap<String, String> = cfg
        .dataset
        .books
        .values()
        .map(|title| (slug_segment(title), title.clone()))
        .collect();

    let titles = inventory_publications(inv);
    let mut rows: BTreeMap<String, Publication> = BTreeMap::new();
    let mut display_by_source: BTreeMap<String, String> = BTreeMap::new();
    for title in &titles {
        let source = canonical_source_id(title);
        if source.is_empty() {
            return Err(vec![format!(
                "publication {title:?} has no canonical source id"
            )]);
        }
        let display = psrd
            .get(&source)
            .cloned()
            .unwrap_or_else(|| title.trim().to_string());
        display_by_source
            .entry(source.clone())
            .and_modify(|current| {
                if display < *current {
                    *current = display.clone();
                }
            })
            .or_insert(display);
    }
    for title in titles {
        let source = canonical_source_id(&title);
        let display = display_by_source
            .get(&source)
            .cloned()
            .unwrap_or_else(|| title.clone());
        rows.insert(
            title,
            Publication {
                source,
                title: display,
            },
        );
    }
    Ok(Registry {
        version: REGISTRY_FORMAT,
        publication: rows,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn psrd_config() -> &'static str {
        "[dataset]\nid = \"psrd-data\"\nrepository = \"r\"\ncommit = \"c\"\ntyped = []\nrules = []\n[dataset.books]\ncore_rulebook = \"Core Rulebook\"\nbestiary = \"Bestiary\"\nbestiary_3 = \"Bestiary 3\"\n"
    }

    #[test]
    fn parses_and_round_trips_with_a_stable_header() {
        let text = "version = 1\n[publication.\"PRPG Core Rulebook\"]\nsource = \"core-rulebook\"\ntitle = \"Core Rulebook\"\n";
        let registry = Registry::parse(text).unwrap();
        let bytes = registry.to_bytes().unwrap();
        let decoded = Registry::parse(std::str::from_utf8(&bytes).unwrap()).unwrap();
        assert_eq!(decoded, registry);
        assert!(
            std::str::from_utf8(&bytes)
                .unwrap()
                .contains("# Canonical publication registry")
        );
    }

    #[test]
    fn rejects_an_unknown_format_and_padded_title() {
        assert!(Registry::parse("version = 99\n[publication]\n").is_err());
        assert!(
            Registry::parse(
                "version = 1\n[publication.\" Core Rulebook\"]\nsource = \"core-rulebook\"\ntitle = \"Core Rulebook\"\n"
            )
            .is_err()
        );
    }

    #[test]
    fn psrd_books_keep_their_source_id_and_display_title() {
        let dir = std::env::temp_dir().join(format!(
            "ci-publications-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap_or_default()
                .as_nanos()
        ));
        std::fs::create_dir_all(&dir).unwrap();
        let config = dir.join("source.toml");
        std::fs::write(&config, psrd_config()).unwrap();
        let inv = Inventory {
            dataset: "d".into(),
            commit: "c".into(),
            input_digest: "0".repeat(64),
            json_files: 0,
            input_records: 0,
            registered_publications: 0,
            by_file: BTreeMap::new(),
            by_shape: BTreeMap::new(),
            by_publication: BTreeMap::new(),
            directives: BTreeMap::new(),
            unregistered_publications: Vec::new(),
            out_of_scope: Vec::new(),
            pi_omissions: Vec::new(),
            records: Vec::new(),
        };
        let registry = generate(&inv, &config).unwrap();
        assert!(registry.publication.is_empty());
        std::fs::remove_dir_all(&dir).unwrap();
    }
}

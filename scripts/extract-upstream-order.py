#!/usr/bin/env python3
"""Extract the upstream sibling order of typed records into sources/psrd-data/upstream-order.json.

The compiler never opens the dataset's SQLite databases. The order of records that no rules
tree contains (spells, feats, creatures, races, skills) exists only in the databases'
`sections.lft` column, the nested-set order, so this script reads it ahead of time, read-only.

For each selected typed record that no selected rules tree nests, it records the position in
document order of its book. Records are written in runs that share an upstream parent, in
the order of the nested set. A child is a name below its parent's url, or a full url.

Run after scripts/expand-sources.py, then commit the result. The compiler reads the file
but does not verify it against the databases; rerun this script after changing the pin.
"""
from pathlib import Path
import json
import sqlite3
import tomllib

root = Path(__file__).resolve().parents[1]
cache = root / '.cache/sources/psrd-data'
config = tomllib.loads((root / 'sources/psrd-data/source.toml').read_text())['dataset']
output = root / 'sources/psrd-data/upstream-order.json'
databases = {
    'advanced_players_guide': 'apg', 'advanced_race_guide': 'arg', 'bestiary': 'b1',
    'bestiary_2': 'b2', 'bestiary_3': 'b3', 'bestiary_4': 'b4', 'core_rulebook': 'cr',
    'game_mastery_guide': 'gmg', 'monster_codex': 'mc', 'mythic_adventures': 'ma',
    'npc_codex': 'npc', 'technology_guide': 'tech', 'ultimate_campaign': 'ucampaign',
    'ultimate_combat': 'uc', 'ultimate_equipment': 'ue', 'ultimate_magic': 'um',
}


def urls_below(node, found):
    if node.get('url'):
        found.add(node['url'])
    for child in node.get('sections') or []:
        urls_below(child, found)


nested = {}
for book in databases:
    found = set()
    for rule in config['rules']:
        if rule.startswith(book + '/'):
            urls_below(json.loads((cache / rule).read_text()), found)
    nested[book] = found

lists = []
total = 0
for book, short in sorted(databases.items()):
    typed = {}
    for directory in config['typed']:
        if not directory.startswith(book + '/'):
            continue
        for path in sorted((cache / directory).rglob('*.json')):
            url = json.loads(path.read_text()).get('url')
            if url and url not in nested[book]:
                typed[url] = path
    if not typed:
        continue
    connection = sqlite3.connect(f'file:{cache}/book-{short}.db?mode=ro', uri=True)
    parents = {pid: url for pid, url in connection.execute('select section_id, url from sections')}
    rows = {}
    for url, parent, lft in connection.execute(
        'select url, parent_id, lft from sections where url is not null order by lft'
    ):
        if url in typed and url not in rows:
            rows[url] = (lft, parents.get(parent) or '')
    missing = sorted(set(typed) - set(rows))
    if missing:
        raise SystemExit(f'{book}: {len(missing)} typed records are not in the database, first {missing[0]}')
    run = None
    for url, (lft, parent) in sorted(rows.items(), key=lambda item: item[1][0]):
        child = url[len(parent) + 1:] if parent and url.startswith(parent + '/') else url
        if run is None or run['parent'] != parent:
            run = {'parent': parent, 'children': []}
            lists.append(run)
        run['children'].append(child)
        total += 1

lines = ['{', '"version": 1,',
         '"note": "Generated by scripts/extract-upstream-order.py from the pinned databases. Do not edit by hand.",',
         '"lists": [']
lines.append(',\n'.join(json.dumps(run, ensure_ascii=False) for run in lists))
lines += [']', '}']
output.write_text('\n'.join(lines) + '\n')
print(f'{total} records in {len(lists)} runs, {output.stat().st_size} bytes')

import { test, expect, loadCorpus } from "./fixtures";
import { installLibrary, waitControlled, waitReady } from "./helpers";
import { readFile } from "node:fs/promises";

test("stars export and import between isolated profiles and survive offline restart", async ({ browser, baseURL, guard, openProfile, server }) => {
  const fireball = [...loadCorpus().entries.values()].find((entry) => entry.title === "Fireball" && entry.kind === "spell");
  if (!fireball) throw new Error("Expected Fireball fixture in the compiled corpus");
  const first = await browser.newContext({ baseURL });
  guard.watch(first);
  const pageA = await first.newPage();
  await installLibrary(pageA); await waitControlled(pageA);
  await pageA.goto(`#/entry/${fireball.id}`);
  await pageA.locator(".bookmark-toggle").click();
  await pageA.goto("#/");
  await pageA.locator(".star-transfer > summary").click();
  const downloadPromise = pageA.waitForEvent("download");
  await pageA.getByRole("button", { name: "Export stars" }).click();
  const download = await downloadPromise;
  const path = await download.path();
  expect(path).toBeTruthy();
  const archiveBytes = await readFile(path!);
  await first.close();

  const second = await openProfile();
  const pageB = await second.newPage();
  await installLibrary(pageB); await waitControlled(pageB);
  await pageB.locator(".star-transfer > summary").click();
  await pageB.locator("#star-archive-file").setInputFiles({ name: "cast-iron-stars.json", mimeType: "application/json", buffer: archiveBytes });
  await expect(pageB.getByRole("status")).toContainText("Imported 1 new star");
  await expect(pageB.locator(".home-bookmarks > li")).toContainText("Fireball");
  await pageB.locator("#star-archive-file").setInputFiles({ name: "cast-iron-stars.json", mimeType: "application/json", buffer: archiveBytes });
  await expect(pageB.getByRole("status")).toContainText("Imported 0 new stars; 1 already present");
  await pageB.locator("#star-archive-file").setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from('{"format":"cast-iron-stars","version":999,"stars":[]}') });
  await expect(pageB.getByRole("alert")).toContainText("not supported");
  await second.close();
  const restarted = await openProfile({ offline: true });
  const pageC = await restarted.newPage();
  await pageC.goto("./"); await waitReady(pageC);
  await expect(pageC.locator(".home-bookmarks > li")).toContainText("Fireball");
  await restarted.close();
});
